"""Phase 4 Part D1: Offline Scoring of Cached Answers.

Scores cached LLM answers generated by api_runner:
1. LLM-only baseline (339 queries: 60 cti-ate, 229 CTI-ATTACK, 50 cti-taa).
2. cti-taa attribution variants (100 queries: 50 V0, 50 V1).
3. E0' generation (31 queries on cti-ate so far).
4. E1b generation (30 queries on cti-ate so far).

Metrics:
- Technique F1 (strict and sub_credit) on cti-ate and CTI-ATTACK.
- Threat Group match (S_exact and S_alias) on cti-taa.
- Per-query CSVs and JSON summary saved to results/phase_4/.
Strictly offline: NO API calls.
"""

