import sys
from pathlib import Path
from typing import Any, Dict, List, Optional, Set, Tuple

import numpy as np
import pandas as pd

REPO_ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(REPO_ROOT))

from src.data_loader import load_benchmark_dataset, load_stix_all_bundles
from src.retrieval_eval import (
    extract_technique_ids_from_text,
    parse_ground_truth_techniques,
    normalize_group_name,
)


def compute_technique_f1(
    pred_techs: Set[str],
    gt_techs: Set[str],
) -> Dict[str, float]:
    """Compute strict and sub_credit Precision, Recall, and F1."""
    if not gt_techs:
        return {
            "p_strict": 0.0, "r_strict": 0.0, "f1_strict": 0.0,
            "p_sub": 0.0, "r_sub": 0.0, "f1_sub": 0.0,
        }

    # 1. Strict match
    tp_strict = len(pred_techs & gt_techs)
    p_strict = tp_strict / len(pred_techs) if pred_techs else 0.0
    r_strict = tp_strict / len(gt_techs)
    f1_strict = (2 * p_strict * r_strict / (p_strict + r_strict)) if (p_strict + r_strict) > 0 else 0.0

    # 2. Sub-technique credits parent match
    credited_pred = set(pred_techs)
    for t in pred_techs:
        if "." in t:
            credited_pred.add(t.split(".")[0])

    tp_sub = len(credited_pred & gt_techs)
    p_sub = tp_sub / len(credited_pred) if credited_pred else 0.0
    r_sub = tp_sub / len(gt_techs)
    f1_sub = (2 * p_sub * r_sub / (p_sub + r_sub)) if (p_sub + r_sub) > 0 else 0.0

    return {
        "p_strict": round(p_strict, 4),
        "r_strict": round(r_strict, 4),
        "f1_strict": round(f1_strict, 4),
        "p_sub": round(p_sub, 4),
        "r_sub": round(r_sub, 4),
        "f1_sub": round(f1_sub, 4),
    }


def score_group_match(
    raw_answer: str,
    gt_raw: str,
    group_alias_map: Dict[str, Dict[str, Any]],
) -> Dict[str, int]:
    """Score whether raw_answer identifies the group under both D1 Scorer Variants.
    
    Returns:
    - v1_exact: Scorer Variant 1 S_exact (first name in GT string)
    - v1_alias: Scorer Variant 1 S_alias (any name parsed from GT string)
    - v2_exact: Scorer Variant 2 S_exact (STIX canonical name or MITRE ID)
    - v2_alias: Scorer Variant 2 S_alias (STIX canonical or any ontology alias)
    """
    # -------------------------------------------------------------------------
    # SCORER VARIANT 1: Text-based Parsing from GT String
    # -------------------------------------------------------------------------
    parts = re.split(r"\(|\)|,|;|/|\balias\b|\balso known as\b|\bor\b|\band\b", gt_raw, flags=re.I)
    v1_candidates = [p.strip(" \t\n\r*\"'") for p in parts if len(p.strip(" \t\n\r*\"'")) >= 3]
    
    v1_exact = 0
    if v1_candidates:
        first_cand = v1_candidates[0]
        if re.search(r"\b" + re.escape(first_cand) + r"\b", raw_answer, re.I):
            v1_exact = 1

    v1_alias = v1_exact
    if v1_alias == 0:
        for cand in v1_candidates:
            if re.search(r"\b" + re.escape(cand) + r"\b", raw_answer, re.I):
                v1_alias = 1
                break

    # -------------------------------------------------------------------------
    # SCORER VARIANT 2: STIX Knowledge Base Ontology-Expanded
    # -------------------------------------------------------------------------
    raw_gt_norm = normalize_group_name(gt_raw)
    gt_canonical_name = None
    gt_canonical_id = None
    all_gt_aliases_text: Set[str] = set()

    for gid, gdata in group_alias_map.items():
        c_norm = normalize_group_name(gdata.get("canonical_name", ""))
        a_norms = {normalize_group_name(a) for a in gdata.get("aliases", [])}
        if raw_gt_norm == c_norm or raw_gt_norm in a_norms or any(a in raw_gt_norm for a in a_norms if len(a) > 3):
            gt_canonical_name = gdata.get("canonical_name", "")
            gt_canonical_id = gid
            all_gt_aliases_text.add(gid)
            all_gt_aliases_text.add(gt_canonical_name)
            all_gt_aliases_text.update(gdata.get("aliases", []))
            break

    v2_exact = 0
    if gt_canonical_id and re.search(r"\b" + re.escape(gt_canonical_id) + r"\b", raw_answer, re.I):
        v2_exact = 1
    elif gt_canonical_name and re.search(r"\b" + re.escape(gt_canonical_name) + r"\b", raw_answer, re.I):
        v2_exact = 1
    elif v1_exact == 1:
        v2_exact = 1

    v2_alias = v2_exact
    if v2_alias == 0:
        for alias in all_gt_aliases_text:
            if len(alias) >= 3 and re.search(r"\b" + re.escape(alias) + r"\b", raw_answer, re.I):
                v2_alias = 1
                break
        if v2_alias == 0 and v1_alias == 1:
            v2_alias = 1

    return {
        "v1_exact": v1_exact,
        "v1_alias": v1_alias,
        "v2_exact": v2_exact,
        "v2_alias": v2_alias,
    }


def main():
    print("=" * 80)
    print("PHASE 4 PART D1: OFFLINE SCORING OF CACHED ANSWERS")
    print("=" * 80)

    out_dir = REPO_ROOT / "results" / "phase_4"
    out_dir.mkdir(parents=True, exist_ok=True)

    cache_dir = REPO_ROOT / ".cache" / "api_runner"
    if not cache_dir.exists():
        print(f"Error: Cache directory {cache_dir} does not exist.")
        return

    # Load Knowledge Base for alias mapping
    print("Loading STIX Knowledge Base for alias map...")
    kb = load_stix_all_bundles()
    group_alias_map = kb.get_group_alias_map()

    # Load benchmark ground truth tables
    print("Loading benchmark datasets...")
    datasets = {
        "cti-ate": load_benchmark_dataset("cti-ate").df,
        "CTI-ATTACK": load_benchmark_dataset("CTI-ATTACK").df,
        "cti-taa": load_benchmark_dataset("cti-taa").df,
    }

    cached_files = sorted(glob.glob(str(cache_dir / "*.json")))
    print(f"Found {len(cached_files)} cached generation files.")

    tech_records = []
    taa_records = []

    for fpath_str in cached_files:
        fpath = Path(fpath_str)
        try:
            with open(fpath, "r", encoding="utf-8") as f:
                data = json.load(f)
        except Exception as e:
            print(f"Error reading {fpath.name}: {e}")
            continue

        arm = data.get("arm", "")
        ds_name = data.get("dataset", "")
        row_idx = data.get("row_idx")
        raw_ans = data.get("raw_answer", "")
        latency_s = data.get("latency_s", 0.0)

        if row_idx is None or ds_name not in datasets:
            continue

        df_ds = datasets[ds_name]
        if row_idx >= len(df_ds):
            continue

        row_gt = str(df_ds.iloc[row_idx].get("ground_truth", ""))
        query_text = str(df_ds.iloc[row_idx].get("query", ""))

        if ds_name in ["cti-ate", "CTI-ATTACK"]:
            # Technique evaluation
            pred_techs = extract_technique_ids_from_text(raw_ans)
            gt_techs = parse_ground_truth_techniques(row_gt)
            f1_scores = compute_technique_f1(pred_techs, gt_techs)

            tech_records.append({
                "arm": arm,
                "dataset": ds_name,
                "row_idx": row_idx,
                "num_gt": len(gt_techs),
                "num_pred": len(pred_techs),
                "p_strict": f1_scores["p_strict"],
                "r_strict": f1_scores["r_strict"],
                "f1_strict": f1_scores["f1_strict"],
                "p_sub": f1_scores["p_sub"],
                "r_sub": f1_scores["r_sub"],
                "f1_sub": f1_scores["f1_sub"],
                "latency_s": latency_s,
                "gt_techs": ";".join(sorted(list(gt_techs))),
                "pred_techs": ";".join(sorted(list(pred_techs))),
            })

        elif ds_name == "cti-taa":
            # Group attribution evaluation
            match_res = score_group_match(raw_ans, row_gt, group_alias_map)
            taa_records.append({
                "arm": arm,
                "dataset": ds_name,
                "row_idx": row_idx,
                "ground_truth": row_gt,
                "v1_exact": match_res["v1_exact"],
                "v1_alias": match_res["v1_alias"],
                "v2_exact": match_res["v2_exact"],
                "v2_alias": match_res["v2_alias"],
                "latency_s": latency_s,
                "ans_preview": raw_ans[:200].replace("\n", " "),
            })

    # Save per-query CSVs
    df_tech = pd.DataFrame(tech_records)
    csv_tech_path = out_dir / "per_query_technique_f1.csv"
    df_tech.to_csv(csv_tech_path, index=False)
    print(f"\nSaved technique per-query CSV ({len(df_tech)} rows) to: {csv_tech_path}", flush=True)

    df_taa = pd.DataFrame(taa_records)
    csv_taa_path = out_dir / "per_query_cti_taa_attribution.csv"
    df_taa.to_csv(csv_taa_path, index=False)
    print(f"Saved cti-taa per-query CSV ({len(df_taa)} rows) to: {csv_taa_path}", flush=True)

    # Compute Summary Aggregates
    summary: Dict[str, Any] = {"technique_f1": {}, "cti_taa_attribution": {}}

    if not df_tech.empty:
        print("\n--- TECHNIQUE EXTRACTION F1 SUMMARY ---", flush=True)
        for (arm, ds), grp in df_tech.groupby(["arm", "dataset"]):
            cell_key = f"{arm}_{ds}"
            mean_f1_strict = float(grp["f1_strict"].mean())
            mean_r_strict = float(grp["r_strict"].mean())
            mean_p_strict = float(grp["p_strict"].mean())
            mean_f1_sub = float(grp["f1_sub"].mean())
            mean_r_sub = float(grp["r_sub"].mean())
            mean_p_sub = float(grp["p_sub"].mean())
            n = len(grp)

            summary["technique_f1"][cell_key] = {
                "arm": arm,
                "dataset": ds,
                "n_queries": n,
                "p_strict": round(mean_p_strict, 4),
                "r_strict": round(mean_r_strict, 4),
                "f1_strict": round(mean_f1_strict, 4),
                "p_sub": round(mean_p_sub, 4),
                "r_sub": round(mean_r_sub, 4),
                "f1_sub": round(mean_f1_sub, 4),
            }
            print(f"[{cell_key}] N={n} | Strict: P={mean_p_strict:.4f}, R={mean_r_strict:.4f}, F1={mean_f1_strict:.4f} | Sub: P={mean_p_sub:.4f}, R={mean_r_sub:.4f}, F1={mean_f1_sub:.4f}", flush=True)

    if not df_taa.empty:
        print("\n--- CTI-TAA THREAT GROUP ATTRIBUTION SUMMARY ---", flush=True)
        for arm, grp in df_taa.groupby("arm"):
            v1_exact_acc = float(grp["v1_exact"].mean())
            v1_alias_acc = float(grp["v1_alias"].mean())
            v2_exact_acc = float(grp["v2_exact"].mean())
            v2_alias_acc = float(grp["v2_alias"].mean())
            n = len(grp)
            summary["cti_taa_attribution"][arm] = {
                "arm": arm,
                "n_queries": n,
                "scorer_v1_text": {
                    "acc_exact": round(v1_exact_acc, 4),
                    "acc_alias": round(v1_alias_acc, 4),
                    "alias_gain": round(v1_alias_acc - v1_exact_acc, 4),
                },
                "scorer_v2_ontology": {
                    "acc_exact": round(v2_exact_acc, 4),
                    "acc_alias": round(v2_alias_acc, 4),
                    "alias_gain": round(v2_alias_acc - v2_exact_acc, 4),
                },
            }
            print(f"[{arm}] N={n} | Scorer V1 (Text): Exact={v1_exact_acc:.4f}, Alias={v1_alias_acc:.4f} (+{v1_alias_acc - v1_exact_acc:.4f}) | Scorer V2 (Ontology): Exact={v2_exact_acc:.4f}, Alias={v2_alias_acc:.4f} (+{v2_alias_acc - v2_exact_acc:.4f})", flush=True)

    json_summary_path = out_dir / "d1_scoring_summary.json"
    with open(json_summary_path, "w", encoding="utf-8") as f:
        json.dump(summary, f, indent=2)
    print(f"\nSaved scoring summary to: {json_summary_path}", flush=True)


if __name__ == "__main__":
    main()
